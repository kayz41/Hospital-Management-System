    private void btnSAVEActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnSAVEActionPerformed
        


    try {

        // ==============================
        // VALIDATION
        // ==============================

        if (!ValidationUtil.required(
                cmbPatient,
                "a patient")) {

            return;
        }

        if (!ValidationUtil.required(
                txtPatientID,
                "Patient ID")) {

            return;
        }

        if (!ValidationUtil.positiveInteger(
                txtAmount,
                "Amount")) {

            return;
        }

        if (!ValidationUtil.required(
                txtPaymentMethod,
                "Payment Method")) {

            return;
        }

       if (!ValidationUtil.optionalDate(
        txtPaymentDate,
        "Payment Date")) {

    return;
}


        // ==============================
        // CREATE MODEL
        // ==============================

        BillingModel model =
                new BillingModel();


        model.setPatientID(
                txtPatientID.getText().trim());


        model.setAmount(
                Integer.parseInt(
                        txtAmount.getText().trim()));


        model.setPaymentMethod(
                txtPaymentMethod.getText().trim());


        model.setPaymentDate(
                txtPaymentDate.getText().trim());


        // ==============================
        // SAVE
        // ==============================

        dao.saveBilling(model);


        // ==============================
        // REFRESH
        // ==============================

        loadBillings();


        JOptionPane.showMessageDialog(
                this,
                "Billing saved successfully.",
                "Success",
                JOptionPane.INFORMATION_MESSAGE);


        clearBillingFields();

    }

    catch (Exception e) {

        e.printStackTrace();

        JOptionPane.showMessageDialog(
                this,
                "Unable to save billing record:\n"
                + e.getMessage(),
                "Error",
                JOptionPane.ERROR_MESSAGE);
    }


    }//GEN-LAST:event_btnSAVEActionPerformed

