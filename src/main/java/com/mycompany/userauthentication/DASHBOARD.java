    private void applyPermissions()
{
    if(UserSession.role == null)
    {
        return;
    }

    if(UserSession.role.equalsIgnoreCase("Doctor"))
    {
        btnDoctors.setVisible(false);
        btnBilling.setVisible(false);
        btnLaboratory.setVisible(false);
        btnStaff.setVisible(false);
        btnUsers.setVisible(false);
    }

    else if(UserSession.role.equalsIgnoreCase("Admin"))
    {
        btnDoctors.setVisible(true);
        btnBilling.setVisible(true);
        btnLaboratory.setVisible(true);
        btnStaff.setVisible(true);
        btnUsers.setVisible(true);
    }
}
    
    
    
    
    
    
    
    
    
    
    private void loadStatistics()
    {
        try
        {
            Connection con = DatabaseConnection.getConnection();
            
            PreparedStatement pst1 =
                    con.prepareStatement("SELECT COUNT(*) FROM Patients");
            
            
            ResultSet rs1 = pst1.executeQuery();
            
            if(rs1.next())
            {
                jLabel7.setText(rs1.getString(1));
            }
            
            PreparedStatement pst2 =
                    con.prepareStatement("SELECT COUNT(*) FROM Doctors");
            
            ResultSet rs2 = pst2.executeQuery();
            
            if(rs2.next())
            {
                jLabel11.setText(rs2.getString(1));
            }
            PreparedStatement pst3 =
                    con.prepareStatement("SELECT COUNT(*) FROM Billing");
            
            ResultSet rs3 = pst3.executeQuery();
            
            if(rs3.next())
            {
                jLabel9.setText(rs3.getString(1));
            }
            PreparedStatement pst4 =
                    con.prepareStatement("SELECT COUNT(*) FROM Appointments");
            ResultSet rs4 = pst4.executeQuery();
            if(rs4.next())
            {
                joel.setText(rs4.getString(1));
            }
            
            PreparedStatement pst5 =
                    con.prepareStatement("SELECT COUNT(*) FROM Staff");
            
            ResultSet rs5 = pst5.executeQuery();
            
            if(rs5.next())
            {
                jLabel21.setText(rs5.getString(1));
            }
            
            PreparedStatement pst6 =
                    con.prepareStatement("SELECT COUNT(*) FROM Users");
            
            ResultSet rs6 = pst6.executeQuery();
            
            if(rs6.next())
            {
                jLabel23.setText(rs6.getString(1));
            }
            
            
            
            
            }
        catch(Exception e)
        {
            JOptionPane.showMessageDialog(this,
                    "Error: " + e.getMessage());
        }
                           
    }
    
    
    private void loadRecentActivity() {
        try{
            Connection con = DatabaseConnection.getConnection();
            
            String sql = 
                    "SELECT TOP 20 AuditID, Username, ActionPerformed, ActionDate " +
                    "FROM AuditTrail ORDER BY ActionDate DESC";
            
            PreparedStatement pst = con.prepareStatement(sql);
            ResultSet rs = pst.executeQuery();
            
            DefaultTableModel model = 
                    (DefaultTableModel) tblRecentActivity.getModel();
            
            model.setRowCount(0);
            
            while(rs.next()){
                
                model.addRow(new Object[]{
                    rs.getInt("AuditID"),
                    rs.getString("Username"),
                    rs.getString("ActionPerformed"),
                    rs.getTimestamp("ActionDate")
                });
                
            }
        }catch(Exception e){
            JOptionPane.showMessageDialog(this, e.getMessage());
        }
    }
                
            
        
    
    
    
    
    
    
