private void loadLaboratoryRecords() {

    try {

        DefaultTableModel model =
                (DefaultTableModel)
                tblLaboratory.getModel();

        model.setRowCount(0);


        ResultSet rs =
                dao.getAllLaboratoryRecords();


        while (rs.next()) {

            model.addRow(
                    new Object[]{

                        rs.getInt("TestID"),

                        rs.getInt("PatientID"),

                        rs.getString(
                                "PatientName"),

                        rs.getInt("DoctorID"),

                        rs.getString(
                                "DoctorName"),

                        rs.getString(
                                "TestName"),

                        rs.getString(
                                "Result"),

                        rs.getString(
                                "TestDate")
                    });
        }


        rs.getStatement()
                .getConnection()
                .close();

    }

    catch (Exception e) {

        JOptionPane.showMessageDialog(
                this,
                "Display Error:\n"
                + e.getMessage(),
                "Laboratory Error",
                JOptionPane.ERROR_MESSAGE);
    }
}
    
    
    
    
    
    
    
    
    
    
    
    
    
    
    
    
    
    
    
    
    
    
    
    
    
    
    
    
    
    
    
    
    
    
    
    
    
    
    
    
    
    
