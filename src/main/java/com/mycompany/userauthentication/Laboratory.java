    private void btnSEARCHActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnSEARCHActionPerformed
                                         

 
    try {

        String keyword =
                txtPatientName
                        .getText()
                        .trim();


        if (keyword.isEmpty()) {

            JOptionPane.showMessageDialog(
                    this,
                    "Enter Patient Name, Doctor Name "
                    + "or Test Name to search.");

            txtPatientName.requestFocusInWindow();

            return;
        }


        DefaultTableModel model =
                (DefaultTableModel)
                tblLaboratory.getModel();


        model.setRowCount(0);


        ResultSet rs =
                dao.searchLaboratoryRecord(
                        keyword);


        while (rs.next()) {

            model.addRow(
                    new Object[]{

                        rs.getInt("TestID"),

                        rs.getInt("PatientID"),

                        rs.getString(
                                "PatientName"),

                        rs.getInt("DoctorID"),

                        rs.getString(
                                "DoctorName"),

                        rs.getString(
                                "TestName"),

                        rs.getString(
                                "Result"),

                        rs.getString(
                                "TestDate")
                    });
        }


        rs.getStatement()
                .getConnection()
                .close();

    }

    catch (Exception e) {

        e.printStackTrace();

        JOptionPane.showMessageDialog(
                this,
                "Search Error:\n"
                + e.getMessage(),
                "Search Error",
                JOptionPane.ERROR_MESSAGE);
    }


    }//GEN-LAST:event_btnSEARCHActionPerformed

