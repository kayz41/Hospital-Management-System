    private void btnLOGINActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnLOGINActionPerformed
       




    try {

        String username =
                txtUSERNAME
                        .getText()
                        .trim();


        String password =
                new String(
                        txtPASSWORD
                                .getPassword());


        /*
         * =====================================
         * BASIC VALIDATION
         * =====================================
         */

        if (username.isEmpty()) {

            JOptionPane.showMessageDialog(
                    this,
                    "Please enter Username.");

            txtUSERNAME.requestFocusInWindow();

            return;
        }


        if (password.isEmpty()) {

            JOptionPane.showMessageDialog(
                    this,
                    "Please enter Password.");

            txtPASSWORD.requestFocusInWindow();

            return;
        }


        Connection con =
                DatabaseConnection.getConnection();


        /*
         * =====================================
         * FIND USER
         * =====================================
         */

        String sql =
                "SELECT UserID, Username, Password, "
              + "Role, FailedAttempts, AccountLocked "
              + "FROM Users "
              + "WHERE Username=?";


        PreparedStatement pst =
                con.prepareStatement(sql);


        pst.setString(
                1,
                username);


        ResultSet rs =
                pst.executeQuery();


        /*
         * =====================================
         * USER NOT FOUND
         * =====================================
         */

        if (!rs.next()) {

            JOptionPane.showMessageDialog(
                    this,
                    "Invalid Username or Password.");

            rs.close();
            pst.close();
            con.close();

            return;
        }


        int userID =
                rs.getInt("UserID");


        String storedUsername =
                rs.getString("Username");


        String storedPassword =
                rs.getString("Password");


        String role =
                rs.getString("Role");


        int failedAttempts =
                rs.getInt("FailedAttempts");


        boolean accountLocked =
                rs.getBoolean("AccountLocked");


        /*
         * =====================================
         * CHECK ACCOUNT LOCK
         * =====================================
         */

        if (accountLocked) {

            JOptionPane.showMessageDialog(
                    this,
                    "This account is locked because "
                  + "of too many failed login attempts.\n\n"
                  + "Please contact an administrator.",
                    "Account Locked",
                    JOptionPane.WARNING_MESSAGE);


            rs.close();
            pst.close();
            con.close();

            return;
        }


        /*
         * =====================================
         * CHECK PASSWORD
         * =====================================
         */

        boolean passwordCorrect =
                BCrypt.checkpw(
                        password,
                        storedPassword);


        /*
         * =====================================
         * SUCCESSFUL LOGIN
         * =====================================
 */

        if (passwordCorrect) {

            String resetSQL =
                    "UPDATE Users "
                  + "SET FailedAttempts=0, "
                  + "AccountLocked=0 "
                  + "WHERE UserID=?";


            PreparedStatement resetPst =
                    con.prepareStatement(
                            resetSQL);


            resetPst.setInt(
                    1,
                    userID);


            resetPst.executeUpdate();


            resetPst.close();


            /*
             * Save session information.
             */

           UserSession.startSession(
        storedUsername,
        role);


            Login.loggedRole =
                    UserSession.role;

            Login.loggedUsername =
                    UserSession.username;


            System.out.println(
                    "Role saved: "
                    + Login.loggedRole);


            /*
             * Audit successful login.
             */

            AuditLogger.log(
                    "User Logged In: "
                    + storedUsername);


            /*
             * Open dashboard.
             */

            DASHBOARD db =
                    new DASHBOARD();


            /*
             * Start the 15-minute
             * inactivity session timer.
             */

            SessionManager.startSession(db);


            db.setVisible(true);


            rs.close();
            pst.close();
            con.close();


            this.dispose();

        }

        else {

            /*
             * =================================
             * FAILED LOGIN
             * =================================
             */

            int newFailedAttempts =
                    failedAttempts + 1;


            /*
             * Lock account after
             * 5 failed attempts.
             */

            if (newFailedAttempts >= 5) {

                String lockSQL =
                        "UPDATE Users "
                      + "SET FailedAttempts=?, "
                      + "AccountLocked=1 "
                      + "WHERE UserID=?";


                PreparedStatement lockPst =
                        con.prepareStatement(
                                lockSQL);


                lockPst.setInt(
                        1,
                        newFailedAttempts);

                lockPst.setInt(
                        2,
                        userID);


                lockPst.executeUpdate();


                lockPst.close();


                AuditLogger.log(
                        "Account Locked: "
                        + storedUsername);


                JOptionPane.showMessageDialog(
                        this,
                        "Too many failed login attempts.\n\n"
                      + "This account has been locked.\n"
                      + "Please contact an administrator.",
                        "Account Locked",
                        JOptionPane.WARNING_MESSAGE);

            }

            else {

                String failedSQL =
                        "UPDATE Users "
                      + "SET FailedAttempts=? "
                      + "WHERE UserID=?";


                PreparedStatement failedPst =
                        con.prepareStatement(
                                failedSQL);


                failedPst.setInt(
                        1,
                        newFailedAttempts);

                failedPst.setInt(
                        2,
                        userID);


                failedPst.executeUpdate();


                failedPst.close();


                int remainingAttempts =
                        5 - newFailedAttempts;


                AuditLogger.log(
                        "Failed Login Attempt: "
                        + storedUsername);


                JOptionPane.showMessageDialog(
                        this,
                        "Invalid Username or Password.\n\n"
                      + "Remaining attempts: "
                      + remainingAttempts,
                        "Login Failed",
                        JOptionPane.WARNING_MESSAGE);
            }


            rs.close();
            pst.close();
            con.close();
        }

    }

    catch (Exception e) {

        e.printStackTrace();

        JOptionPane.showMessageDialog(
                this,
                "Login Error:\n"
              + e.getMessage(),
                "Login Error",
                JOptionPane.ERROR_MESSAGE);
    }




        
    
    }//GEN-LAST:event_btnLOGINActionPerformed

