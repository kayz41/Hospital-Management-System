    private void btnDISPLAYActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnDISPLAYActionPerformed
        
                                           

    try {

        Connection con =
                DatabaseConnection.getConnection();


        String sql =
                "SELECT RecordID, PatientID, PatientName, "
                + "DoctorID, DoctorName, Diagnosis, Treatment, "
                + "Prescription, MedicalHistory, Allergies "
                + "FROM MedicalRecords";


        PreparedStatement pst =
                con.prepareStatement(sql);


        ResultSet rs =
                pst.executeQuery();


        DefaultTableModel model =
                (DefaultTableModel)
                tblMedicalRecords.getModel();


        model.setRowCount(0);


        while(rs.next()) {

            model.addRow(new Object[]{

                rs.getInt("RecordID"),

                rs.getInt("PatientID"),

                rs.getString("PatientName"),

                rs.getInt("DoctorID"),

                rs.getString("DoctorName"),

                rs.getString("Diagnosis"),

                rs.getString("Treatment"),

                rs.getString("Prescription"),

                rs.getString("MedicalHistory"),

                rs.getString("Allergies")

            });

        }


        rs.close();
        pst.close();
        con.close();


    }
    catch(Exception e) {

        JOptionPane.showMessageDialog(this,
                "Error: " + e.getMessage());

    }


       
        
      
    }//GEN-LAST:event_btnDISPLAYActionPerformed

    private void btnDELETEActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnDELETEActionPerformed
        
                                       

    if(txtRecordID.getText().trim().isEmpty()) {

        JOptionPane.showMessageDialog(this,
                "Please enter Record ID.");

        return;
    }


    int choice =
            JOptionPane.showConfirmDialog(
                    this,
                    "Are you sure you want to delete this Medical Record?",
                    "Confirm Delete",
                    JOptionPane.YES_NO_OPTION);


    if(choice != JOptionPane.YES_OPTION) {

        return;
    }


    try {

        Connection con =
                DatabaseConnection.getConnection();


        String sql =
                "DELETE FROM MedicalRecords WHERE RecordID=?";


        PreparedStatement pst =
                con.prepareStatement(sql);


        pst.setInt(1,
                Integer.parseInt(txtRecordID.getText()));


        int rows =
                pst.executeUpdate();


        if(rows > 0) {

            JOptionPane.showMessageDialog(this,
                    "Medical Record Deleted Successfully!");


            AuditLogger.log("Deleted Medical Record");


            txtRecordID.setText("");
            txtPatientID.setText("");
            txtPatientName.setText("");
            txtDoctorID.setText("");
            txtDoctorName.setText("");
            txtDiagnosis.setText("");
            txtTreatment.setText("");
            txtPrescription.setText("");
            txtMedicalHistory.setText("");
            txtAllergies.setText("");

        }
        else {

            JOptionPane.showMessageDialog(this,
                    "Medical Record Not Found!");

        }


        pst.close();
        con.close();


    }
    catch(NumberFormatException e) {

        JOptionPane.showMessageDialog(this,
                "Record ID must contain numbers only.");

    }
    catch(Exception e) {

        JOptionPane.showMessageDialog(this,
                "Error: " + e.getMessage());

    }


        
    }//GEN-LAST:event_btnDELETEActionPerformed

