    private void btnDISPLAYActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnDISPLAYActionPerformed
      try{
          Connection con = DatabaseConnection.getConnection();
          
          String sql = "SELECT * FROM Patients";
          
          PreparedStatement pst = con.prepareStatement(sql);
          
          ResultSet rs = pst.executeQuery();
          
          DefaultTableModel model = 
                  (DefaultTableModel) tblPatients.getModel();
          model.setRowCount(0);
          
          while(rs.next())
          {
              model.addRow(new Object[]
              {
                  rs.getInt("PatientID"),
                  rs.getString("PatientName"),
                  rs.getString("Doctor"),
                  rs.getInt("PhoneNumber"),
                  rs.getString("EmailAddress")
              
              });
          }
      }
      catch(Exception e)
      {
          JOptionPane.showMessageDialog(this,
                  "Error: "+ e.getMessage());
          
      }
     
      
      
    }//GEN-LAST:event_btnDISPLAYActionPerformed

    private void btnUPDATEActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnUPDATEActionPerformed
       
        try{
            Connection con = DatabaseConnection.getConnection();
            
            String sql = "UPDATE Patients SET PatientName=?, Doctor=?, PhoneNumber=?, EmailAddress=? WHERE PatientID=?";
            PreparedStatement pst = con. prepareStatement(sql);
            
            pst.setString(1, txtPatientName.getText());
            pst.setString(2, cmbDoctor.getSelectedItem().toString());
            pst.setString(3, txtPhoneNumber.getText());
            pst.setString(4,txtEmailAddress.getText());
            pst.setInt(5,
                    Integer.parseInt(txtPatientID.getText()));
            
            int rows = pst.executeUpdate();
            
            if(rows > 0)
            {
                JOptionPane.showMessageDialog(this,
                        "Patient Updated Successfully!");
                
                AuditLogger.log("Updated Patient");
            }
            else
            {
                JOptionPane.showMessageDialog(this,
                        "Patient Not Found!");
            }
        }
        catch(Exception e)
        {
            JOptionPane.showMessageDialog(this,
                    "Error: " + e.getMessage());
          
        }
        
 
        
        
    }//GEN-LAST:event_btnUPDATEActionPerformed

    private void btnDELETEActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnDELETEActionPerformed
       try{
           Connection con = DatabaseConnection.getConnection();
           int choice = JOptionPane.showConfirmDialog(
           this,
                   "Are you sure you want to delete this Patient?",
                   "Confirm Delete",
                   JOptionPane.YES_NO_OPTION);
           
           if(choice == JOptionPane.YES_OPTION)
           {
               String sql = "DELETE FROM Patients WHERE PatientID=?";
               
               PreparedStatement pst =
                       con.prepareStatement(sql);
               
               
               pst.setInt(1,
                       Integer.parseInt(txtPatientID.getText()));
               
               int rows = pst.executeUpdate();
               
               if(rows > 0)
               {
                   JOptionPane.showMessageDialog(this,
                           "Patient Deleted Successfully!");
                   
                   AuditLogger.log("Deleted Patient");
                   
                   txtPatientID.setText("");
                   txtPatientName.setText("");
                   cmbDoctor.setSelectedIndex(0);
                   txtPhoneNumber.setText("");
                   txtEmailAddress.setText("");
               }
               else
               {
                   JOptionPane.showMessageDialog(this,
                           "Patient Not FOund!");
                   
                      
               }
               
               
           }
       }
       catch(Exception e)
       {
           JOptionPane.showMessageDialog(this,
                   "Error:" + e.getMessage());
       }
       
   
        
    }//GEN-LAST:event_btnDELETEActionPerformed

