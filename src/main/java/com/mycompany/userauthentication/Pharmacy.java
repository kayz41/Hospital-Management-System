   private void loadMedicine() {

    try {

        DefaultTableModel model =
                (DefaultTableModel)
                tblPharmacy.getModel();

        model.setRowCount(0);


        ResultSet rs =
                dao.getAllMedicine();


        while (rs.next()) {

            model.addRow(
                    new Object[]{

                        rs.getInt(
                                "MedicineID"),

                        rs.getString(
                                "MedicineName"),

                        rs.getString(
                                "Supplier"),

                        rs.getDouble(
                                "Price"),

                        rs.getInt(
                                "Quantity"),

                        rs.getString(
                                "ExpiryDate")
                    });
        }


        rs.getStatement()
                .getConnection()
                .close();

    }

    catch (Exception e) {

        JOptionPane.showMessageDialog(
                this,
                "Display Error:\n"
                + e.getMessage(),
                "Pharmacy Error",
                JOptionPane.ERROR_MESSAGE);
    }
}
    
