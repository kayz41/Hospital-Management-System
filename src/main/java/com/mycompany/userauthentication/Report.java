    private void btnSummaryActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnSummaryActionPerformed
try{
    DefaultTableModel model = new DefaultTableModel();
    
    model.addColumn("Module");
    model.addColumn("Total Records");
    
    Connection con = DatabaseConnection.getConnection();
    
    String[] tables = {
        "Patients",
        "Doctors",
        "Staff",
        "Appointments",
        "Billing",
        "Users"
    };
    
    for(String table : tables)
    {
        PreparedStatement pst =
                con.prepareStatement(
                "SELECT COUNT(*) FROM " + table);
        
        ResultSet rs = pst.executeQuery();
        
        if(rs.next())
        {
            model.addRow(new Object[]{
                table,
                rs.getInt(1)
            });
        }
    }
    tblReports.setModel(model);
}
catch(Exception e)
{
    JOptionPane.showMessageDialog(
    this,
            "Error: " + e.getMessage()
    );
}
            
    
    
        
    }//GEN-LAST:event_btnSummaryActionPerformed

