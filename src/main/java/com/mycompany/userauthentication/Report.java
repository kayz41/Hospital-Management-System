    private void btnGenerateReportActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnGenerateReportActionPerformed
      
        try
{
    Connection con = DatabaseConnection.getConnection();

    String reportType =
            cmbReportType.getSelectedItem().toString();

    String sql;

    if(reportType.trim().equalsIgnoreCase("Billing report"))
    {
        sql = "SELECT * FROM Billing";
    }
    else if(reportType.trim().equalsIgnoreCase("Appointments Report"))
    {
        sql = "SELECT * FROM Appointments";
    }
    else if(reportType.trim().equalsIgnoreCase("Doctors Report"))
    {
        sql = "SELECT * FROM Doctors";
    }
    else if(reportType.trim().equalsIgnoreCase("Patients Report"))
    {
        sql = "SELECT * FROM Patients";
    }
    else
    {
        JOptionPane.showMessageDialog(this,
                "Unknown Report Type!");
        return;
    }

    PreparedStatement pst =
            con.prepareStatement(sql);

    ResultSet rs = pst.executeQuery();

    DefaultTableModel model =
            (DefaultTableModel) tblReports.getModel();

    model.setRowCount(0);

    while(rs.next())
    {
        if(reportType.trim().equalsIgnoreCase("Appointments Report"))
        {
            model.addRow(new Object[]
            {
                rs.getObject(1),
                rs.getObject(2),
                rs.getObject(3),
                rs.getObject(4),
                rs.getObject(5),
                rs.getObject(6),
                rs.getObject(7),
                rs.getObject(8)
            });
        }
        else if(reportType.trim().equalsIgnoreCase("Billing Report"))
        {
            model.addRow(new Object[]
            {
                rs.getObject(1),
                rs.getObject(2),
                rs.getObject(3),
                rs.getObject(4)
            });
        }
        else if(reportType.trim().equalsIgnoreCase("Doctors Report"))
        {
            model.addRow(new Object[]
            {
                rs.getObject(1),
                rs.getObject(2),
                rs.getObject(3),
                rs.getObject(4),
                rs.getObject(5)
            });
        }
        else if(reportType.trim().equalsIgnoreCase("Patients Report"))
        {
            model.addRow(new Object[]
            {
                rs.getObject(1),
                rs.getObject(2),
                rs.getObject(3),
                rs.getObject(4)
               
            });
        }
       
        
        
      
    }

    JOptionPane.showMessageDialog(this,
            "Report Generated Successfully!");
}
catch(Exception e)
{
    JOptionPane.showMessageDialog(this,
            "Error: " + e.getMessage());
}

     
         
    }//GEN-LAST:event_btnGenerateReportActionPerformed

