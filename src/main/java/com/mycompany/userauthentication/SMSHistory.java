    private void loadDateTime() {

    Timer timer = new Timer(1000, e -> {

        SimpleDateFormat sdf =
                new SimpleDateFormat("dd/MM/yyyy HH:mm:ss");

        lblDateTime.setText(sdf.format(new Date()));

    });

    timer.start();

}
    
    
    
    
    
    
    
    
    
    
    
    
    
    
    
    
    

