    private void btnSAVEActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnSAVEActionPerformed

        try{
            Connection con = DatabaseConnection.getConnection();

            String sql = "INSERT INTO Staff (StaffName, Position, Phone, Email, Shift,Salary)" +
            "VALUES (?,?,?,?,?,?)";

            PreparedStatement pst = con.prepareStatement(sql);

            pst.setString(1,txtStaffName.getText());
            pst.setString(2, txtPosition.getText());
            pst.setString(3,txtPhone.getText());
            pst.setString(4, txtEmail.getText());
            pst.setString(5,txtShift.getText());
            pst.setString(6, txtSalary.getText());

            pst.executeUpdate();

            JOptionPane.showMessageDialog(this, "Staff Record Saved Successfully!");
            
             AuditLogger.log("Added Staff");

        }

        catch(Exception e)
        {
            JOptionPane.showMessageDialog(this,
                "Error: " + e.getMessage());

        }
    }//GEN-LAST:event_btnSAVEActionPerformed

