    private void btnDELETEActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnDELETEActionPerformed

        int confirm = JOptionPane.showConfirmDialog(
            this,
            "Are you sure you want to delete this record?",
            "Confirm Deletion",
            JOptionPane.YES_NO_OPTION
        );
        if (confirm == JOptionPane.YES_OPTION){
            try{
                Connection con = DatabaseConnection.getConnection();

                String sql = "DELETE FROM Staff WHERE StaffID=?";

                PreparedStatement pst = con.prepareStatement(sql);

                pst.setInt(1, Integer.parseInt(txtStaffID.getText()));

                pst.executeUpdate();

                JOptionPane.showMessageDialog(this, "Staff Record Deleted Successfully!");
                
                AuditLogger.log("Deleted Staff");

            } catch (Exception e) {
                JOptionPane.showMessageDialog(this, "Error: " + e.getMessage());
            }
        }

    }//GEN-LAST:event_btnDELETEActionPerformed

    private void btnSEARCHActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnSEARCHActionPerformed

        try{
            Connection con = DatabaseConnection.getConnection();
            String sql = "SELECT * FROM Staff WHERE StaffID =?";

            PreparedStatement pst = con.prepareStatement(sql);

            pst.setInt(1,
                Integer.parseInt(txtStaffID.getText()));

            ResultSet rs = pst.executeQuery();

            if(rs.next())
            {
                txtStaffName.setText(rs.getString("StaffName"));
                txtPosition.setText(rs.getString("Position"));
                txtShift.setText(rs.getString("Shift"));
                txtEmail.setText(rs.getString("Email"));
                txtPhone.setText(rs.getString("Phone"));
                txtSalary.setText(rs.getString("Salary"));

            }
            else
            {
                JOptionPane.showMessageDialog(this,
                    "Staff Record Not Found!");
            }
        }
        catch(Exception e)
        {
            JOptionPane.showMessageDialog(this,
                "Error: " + e.getMessage());
        }
    }//GEN-LAST:event_btnSEARCHActionPerformed

    private void btnDISPLAYActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnDISPLAYActionPerformed

        try{
            Connection con = DatabaseConnection.getConnection();

            String sql = "SELECT * FROM Staff";

            PreparedStatement pst = con.prepareStatement(sql);

            ResultSet rs = pst.executeQuery();

            DefaultTableModel model =
            (DefaultTableModel) tblStaff.getModel();
            model.setRowCount(0);

            while(rs.next())
            {
                model.addRow(new Object[]
                    {
                        rs.getObject(1),
                        rs.getObject(2),
                        rs.getObject(3),
                        rs.getObject(4),
                        rs.getObject(5),
                        rs.getObject(6),
                        rs.getObject(7)

                    });
                }
            }
            catch(Exception e)
            {
                JOptionPane.showMessageDialog(this,
                    "Error: "+ e.getMessage());

            }
    }//GEN-LAST:event_btnDISPLAYActionPerformed

