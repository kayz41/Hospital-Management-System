    private void btnDELETEActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnDELETEActionPerformed
     


    try {

        String userIDText =
                txtUSERID
                        .getText()
                        .trim();


        if (userIDText.isEmpty()) {

            JOptionPane.showMessageDialog(
                    this,
                    "Please enter User ID.");

            return;
        }


        int userID;

        try {

            userID =
                    Integer.parseInt(
                            userIDText);

        }

        catch (NumberFormatException e) {

            JOptionPane.showMessageDialog(
                    this,
                    "User ID must be a valid number.");

            return;
        }


        int confirm =
                JOptionPane.showConfirmDialog(
                        this,
                        "Are you sure you want to delete "
                        + "this user?\n\n"
                        + "User ID: "
                        + userID,
                        "Confirm User Deletion",
                        JOptionPane.YES_NO_OPTION,
                        JOptionPane.WARNING_MESSAGE);


        if (confirm != JOptionPane.YES_OPTION) {

            return;
        }


        Connection con =
                DatabaseConnection.getConnection();


        /*
         * =====================================
         * CHECK WHETHER USER EXISTS
         * =====================================
         */

        String checkSQL =
                "SELECT Username "
              + "FROM Users "
              + "WHERE UserID=?";


        PreparedStatement checkPst =
                con.prepareStatement(
                        checkSQL);


        checkPst.setInt(
                1,
                userID);


        ResultSet checkRs =
                checkPst.executeQuery();


        if (!checkRs.next()) {

            JOptionPane.showMessageDialog(
                    this,
                    "User not found.");

            checkRs.close();
            checkPst.close();
            con.close();

            return;
        }


        String username =
                checkRs.getString(
                        "Username");


        checkRs.close();
        checkPst.close();


        /*
         * =====================================
         * DELETE USER
         * =====================================
         */

        String sql =
                "DELETE FROM Users "
              + "WHERE UserID=?";


        PreparedStatement pst =
                con.prepareStatement(
                        sql);


        pst.setInt(
                1,
                userID);


        int rowsDeleted =
                pst.executeUpdate();


        pst.close();
        con.close();


        if (rowsDeleted > 0) {

            JOptionPane.showMessageDialog(
                    this,
                    "User Deleted Successfully!");


            AuditLogger.log(
                    "Deleted User: "
                    + username);


            /*
             * =================================
             * CLEAR FORM
             * =================================
             */

            txtUSERID.setText("");

            txtUSERNAME.setText("");

            txtPASSWORD.setText("");

            cmbRole.setSelectedIndex(0);


            /*
             * =================================
             * REFRESH TABLE
             * =================================
             */

            btnDISPLAY.doClick();

        }

        else {

            JOptionPane.showMessageDialog(
                    this,
                    "User deletion failed.");

        }

    }

    catch (Exception e) {

        e.printStackTrace();

        JOptionPane.showMessageDialog(
                this,
                "Delete Error:\n"
                + e.getMessage());
    }


    }//GEN-LAST:event_btnDELETEActionPerformed

    private void btnSEARCHActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnSEARCHActionPerformed

     


    try {

        String userIDText =
                txtUSERID
                        .getText()
                        .trim();


        if (userIDText.isEmpty()) {

            JOptionPane.showMessageDialog(
                    this,
                    "Please enter User ID.");

            return;
        }


        int userID;

        try {

            userID =
                    Integer.parseInt(
                            userIDText);

        }

        catch (NumberFormatException e) {

            JOptionPane.showMessageDialog(
                    this,
                    "User ID must be a valid number.");

            return;
        }


        Connection con =
                DatabaseConnection.getConnection();


        String sql =
                "SELECT UserID, Username, Role "
              + "FROM Users "
              + "WHERE UserID=?";


        PreparedStatement pst =
                con.prepareStatement(
                        sql);


        pst.setInt(
                1,
                userID);


        ResultSet rs =
                pst.executeQuery();


        if (rs.next()) {

            /*
             * =================================
             * LOAD USER INFORMATION
             * =================================
             */

            txtUSERID.setText(
                    String.valueOf(
                            rs.getInt(
                                    "UserID")));


            txtUSERNAME.setText(
                    rs.getString(
                            "Username"));


            /*
             * Password is intentionally NOT
             * loaded into the password field.
             *
             * The database contains a BCrypt
             * hash, not the original password.
             */

            txtPASSWORD.setText("");


            cmbRole.setSelectedItem(
                    rs.getString(
                            "Role"));


        }

        else {

            JOptionPane.showMessageDialog(
                    this,
                    "User Not Found.");

            txtUSERNAME.setText("");

            txtPASSWORD.setText("");

            cmbRole.setSelectedIndex(0);
        }


        rs.close();
        pst.close();
        con.close();

    }

    catch (Exception e) {

        e.printStackTrace();

        JOptionPane.showMessageDialog(
                this,
                "Search Error:\n"
                + e.getMessage());
    }


    }//GEN-LAST:event_btnSEARCHActionPerformed

    private void btnDISPLAYActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnDISPLAYActionPerformed



    try {

        Connection con =
                DatabaseConnection.getConnection();


        /*
         * ==========================================
         * SELECT ONLY SAFE DISPLAY COLUMNS
         * ==========================================
         *
         * Password is deliberately NOT selected.
         */

        String sql =
                "SELECT UserID, Username, Role "
              + "FROM Users "
              + "ORDER BY UserID";


        PreparedStatement pst =
                con.prepareStatement(sql);


        ResultSet rs =
                pst.executeQuery();


        /*
         * ==========================================
         * TABLE MODEL
         * ==========================================
         */

        DefaultTableModel model =
                (DefaultTableModel)
                tblUsers.getModel();


        model.setRowCount(0);


        /*
         * ==========================================
         * LOAD USERS
         * ==========================================
         */

        while (rs.next()) {

            model.addRow(
                    new Object[]{

                        rs.getInt(
                                "UserID"),

                        rs.getString(
                                "Username"),

                        rs.getString(
                                "Role")
                    });
        }


        /*
         * ==========================================
         * CLOSE DATABASE RESOURCES
         * ==========================================
         */

        rs.close();

        pst.close();

        con.close();

    }

    catch (Exception e) {

        JOptionPane.showMessageDialog(
                this,
                "Display Error: "
              + e.getMessage());

        e.printStackTrace();
    }

    }//GEN-LAST:event_btnDISPLAYActionPerformed

