    private void btnDELETEActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnDELETEActionPerformed
        int confirm = JOptionPane.showConfirmDialog(
            this,
            "Are you sure want to delete this User?",
            "Confirm Deletion",
            JOptionPane.YES_NO_OPTION
        );
        if (confirm ==JOptionPane.YES_OPTION){
            try
            {
                Connection con = DatabaseConnection.getConnection();

                String sql =
                "DELETE FROM Users WHERE UserID=?";

                PreparedStatement pst =
                con.prepareStatement(sql);

                pst.setInt(1,
                    Integer.parseInt(txtUSERID.getText()));

                pst.executeUpdate();

                JOptionPane.showMessageDialog(this,
                    "User Deleted Successfully");
                
                AuditLogger.log("Deleted User");
            }
            catch(Exception e)
            {
                JOptionPane.showMessageDialog(this,
                    "Error : " + e.getMessage());
            }
        }
    }//GEN-LAST:event_btnDELETEActionPerformed

    private void btnSEARCHActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnSEARCHActionPerformed

        try{
            Connection con = DatabaseConnection.getConnection();
            String sql = "SELECT * FROM Users WHERE UserID =?";

            PreparedStatement pst = con.prepareStatement(sql);

            pst.setInt(1,
                Integer.parseInt(txtUSERID.getText()));

            ResultSet rs = pst.executeQuery();

            if(rs.next())
            {
                txtUSERID.setText(rs.getString("UserName"));
                txtUSERNAME.setText(rs.getString("Password"));     
                cmbRole.setSelectedItem(rs.getString("Role"));
 
            }
            else
            {
                JOptionPane.showMessageDialog(this,
                    "User Not Found!");
            }
        }
        catch(Exception e)
        {
            JOptionPane.showMessageDialog(this,
                "Error: " + e.getMessage());
        }
    }//GEN-LAST:event_btnSEARCHActionPerformed

    private void btnDISPLAYActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnDISPLAYActionPerformed

        try{
            Connection con = DatabaseConnection.getConnection();

            String sql = "SELECT * FROM Users";

            PreparedStatement pst = con.prepareStatement(sql);

            ResultSet rs = pst.executeQuery();

            DefaultTableModel model =
            (DefaultTableModel) tblUsers.getModel();
            model.setRowCount(0);

            while(rs.next())
            {
                model.addRow(new Object[]
                    {
                        rs.getObject(1),
                        rs.getObject(2),
                        rs.getObject(3),
                        rs.getObject(4)


                    });
                }
            }
            catch(Exception e)
            {
                JOptionPane.showMessageDialog(this,
                    "Error: "+ e.getMessage());

            }
    }//GEN-LAST:event_btnDISPLAYActionPerformed

